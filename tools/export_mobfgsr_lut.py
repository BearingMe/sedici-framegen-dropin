"""Offline export of MobFGSR's single-channel ZIP EXR LUT; Python stdlib only.

Origin: Mob-FGSR/MobFGSR df7ed207ed66d53dc44518ce12572cd49015c125,
resources/lut.exr, CC BY-NC 4.0. Never modifies the reference checkout.
Usage: python tools/export_mobfgsr_lut.py INPUT.exr OUTPUT.h
"""

import hashlib
import pathlib
import struct
import sys
import zlib


def export(source, destination):
    data = pathlib.Path(source).read_bytes()
    if data[:8] != b"\x76\x2f\x31\x01\x02\x00\x00\x00":
        raise ValueError("expected a version-2 scanline EXR")
    offset = 8
    attributes = {}
    while data[offset]:
        end = data.index(0, offset)
        name = data[offset:end].decode("ascii")
        offset = end + 1
        end = data.index(0, offset)
        kind = data[offset:end].decode("ascii")
        offset = end + 1
        size, = struct.unpack_from("<I", data, offset)
        offset += 4
        attributes[name] = (kind, data[offset:offset + size])
        offset += size
    offset += 1
    if attributes["compression"][1] != b"\x03":
        raise ValueError("expected ZIP, 16 scanlines per chunk")
    channels = attributes["channels"][1]
    if channels != b"A\x00\x02\x00\x00\x00\x00\x00\x00\x00\x01\x00\x00\x00\x01\x00\x00\x00\x00":
        raise ValueError("expected only one FLOAT channel, A, with unit sampling")
    if struct.unpack("<4i", attributes["dataWindow"][1]) != (0, 0, 127, 127):
        raise ValueError("expected a 128x128 data window")
    pixels = bytearray(128 * 128 * 4)
    seen = set()
    for chunk in range(8):
        location, = struct.unpack_from("<Q", data, offset + chunk * 8)
        y, size = struct.unpack_from("<iI", data, location)
        if y not in range(0, 128, 16) or y in seen:
            raise ValueError("invalid scanline block")
        seen.add(y)
        block = data[location + 8:location + 8 + size]
        expected = 128 * 16 * 4
        if len(block) < expected:
            decoded = bytearray(zlib.decompress(block))
            if len(decoded) != expected:
                raise ValueError("invalid decompressed size")
            # Undo ZIP's predictor, then byte de-interleave.
            for i in range(1, len(decoded)):
                decoded[i] = (decoded[i - 1] + decoded[i] - 128) & 255
            block = bytearray(expected)
            half = (expected + 1) // 2
            block[0::2] = decoded[:half]
            block[1::2] = decoded[half:]
        if len(block) != expected:
            raise ValueError("invalid block size")
        pixels[y * 128 * 4:(y + 16) * 128 * 4] = block
    values = struct.unpack("<16384f", pixels)
    if not all(-100.0 < x < 100.0 for x in values):
        raise ValueError("non-finite or implausible LUT weights")
    bits = struct.unpack("<16384I", pixels)
    lines = [
        "// Generated by tools/export_mobfgsr_lut.py; do not edit.",
        "// Mob-FGSR/MobFGSR df7ed207ed66d53dc44518ce12572cd49015c125",
        "// resources/lut.exr; CC BY-NC 4.0 (see references/sources/mobfgsr/LICENSE).",
        "// Input SHA256: " + hashlib.sha256(data).hexdigest(),
        "#pragma once", "#include <cstdint>", "namespace sedici::fg {",
        "inline constexpr uint32_t kLutBits[128 * 128] = {",
    ]
    for start in range(0, len(bits), 8):
        lines.append("    " + ", ".join(f"0x{x:08x}u" for x in bits[start:start + 8]) + ",")
    lines.extend(["};", "} // namespace sedici::fg", ""])
    pathlib.Path(destination).write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Exported 128x128 FLOAT LUT; min={min(values):.6f}, max={max(values):.6f}")


if __name__ == "__main__":
    export(*sys.argv[1:])
