"""One-off conversion of the C++ LUT header to the Rust port's binary asset.

Origin: src/generator/lut_data.h (itself generated by tools/export_mobfgsr_lut.py from
Mob-FGSR/MobFGSR df7ed207ed66d53dc44518ce125 resources/lut.exr, CC BY-NC 4.0). This script only
re-packs the same bits; it does not touch the reference checkout or the network.

The atlas is 128x128 single-channel FLOAT texels (16384 x 4 bytes = 64 KiB), sampled by the warp
pass on a 32-texel grid with 4x4 weights. (AGENTS.md describes it as "32x32x16 LUT (~16 KB)";
that is the effective 32x32 sample grid, not the stored atlas.)

Usage: python -I tools/extract_lut_bin.py INPUT.h OUTPUT.bin
"""

import hashlib
import pathlib
import re
import struct
import sys


def extract(source, destination):
    text = pathlib.Path(source).read_text(encoding="utf-8")
    body = re.search(r"kLutBits\[128 \* 128\] = \{(.*?)\};", text, re.S)
    if not body:
        raise ValueError("kLutBits[128 * 128] initializer not found")
    values = re.findall(r"0x([0-9a-fA-F]{8})u", body.group(1))
    if len(values) != 128 * 128:
        raise ValueError(f"expected 16384 texels, found {len(values)}")
    data = b"".join(struct.pack("<I", int(value, 16)) for value in values)
    pathlib.Path(destination).write_bytes(data)
    print(f"Wrote {len(data)} bytes; source sha256 {hashlib.sha256(data).hexdigest()}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    extract(sys.argv[1], sys.argv[2])
